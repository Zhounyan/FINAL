-- ---------------------------------------------------------------------------
-- Enumerated types
-- ---------------------------------------------------------------------------
create type public.app_role as enum ('owner', 'admin', 'staff');

-- stock_in    : products received (supplier deliveries, opening stock, returns)
-- sale        : products sold to customers (always generated by record_sale)
-- damaged     : damaged / unusable products
-- lost        : missing inventory
-- other_out   : other authorised releases
-- adjustment  : authorised corrections (+/-), incl. reversals of earlier entries
-- reclassify  : category transfer pair written when a product changes category
--               (net zero for the product; keeps category balances correct)
create type public.movement_type as enum
  ('stock_in', 'sale', 'damaged', 'lost', 'other_out', 'adjustment', 'reclassify');

-- ---------------------------------------------------------------------------
-- Users (application profile for each Supabase Auth user)
-- ---------------------------------------------------------------------------
create table public.profiles (
  id                    uuid primary key references auth.users (id) on delete cascade,
  email                 text not null,
  full_name             text not null check (char_length(btrim(full_name)) between 2 and 120),
  phone                 text check (phone is null or char_length(phone) <= 40),
  role                  public.app_role not null,
  is_active             boolean not null default true,
  can_add_products      boolean not null default false,   -- staff authorisation flag
  must_change_password  boolean not null default false,
  last_login_at         timestamptz,
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now(),
  created_by            uuid references public.profiles (id) on delete set null
);
create unique index profiles_email_key on public.profiles (lower(email));
create index profiles_created_at_idx on public.profiles (created_at desc);

-- One row only, ever. Its existence permanently closes the public initial setup.
create table public.setup_state (
  singleton     boolean primary key default true check (singleton),
  admin_id      uuid references public.profiles (id) on delete set null,
  completed_at  timestamptz not null default now()
);

-- Brute-force protection for the login edge function (service role only).
create table public.auth_lockouts (
  email          text primary key,
  failed_count   integer not null default 0,
  locked_until   timestamptz,
  last_failed_at timestamptz
);

