-- ---------------------------------------------------------------------------
-- Master data
-- ---------------------------------------------------------------------------
create table public.categories (
  id           bigint generated always as identity primary key,
  name         text not null check (char_length(btrim(name)) between 1 and 80),
  description  text check (description is null or char_length(description) <= 500),
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  created_by   uuid references public.profiles (id) on delete set null
);
create unique index categories_name_key on public.categories (lower(btrim(name)));

create table public.products (
  id               bigint generated always as identity primary key,
  sku              text not null check (char_length(btrim(sku)) between 1 and 64),
  name             text not null check (char_length(btrim(name)) between 1 and 150),
  category_id      bigint not null references public.categories (id) on delete restrict,
  description      text check (description is null or char_length(description) <= 1000),
  unit             text not null default 'pc' check (char_length(btrim(unit)) between 1 and 20),
  purchase_price   numeric(12,2) not null default 0 check (purchase_price >= 0),
  selling_price    numeric(12,2) not null default 0 check (selling_price >= 0),
  -- Maintained exclusively by the stock movement ledger (see triggers).
  current_stock    integer not null default 0 check (current_stock >= 0),
  min_stock_level  integer not null default 0 check (min_stock_level >= 0),
  is_archived      boolean not null default false,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  created_by       uuid references public.profiles (id) on delete set null
);
create unique index products_sku_key on public.products (lower(btrim(sku)));
create index products_created_at_idx on public.products (created_at desc, id desc);
create index products_category_idx on public.products (category_id);
create index products_name_idx on public.products (lower(name));

create table public.customers (
  id              bigint generated always as identity primary key,
  full_name       text not null check (char_length(btrim(full_name)) between 2 and 120),
  contact_number  text check (contact_number is null or char_length(contact_number) <= 40),
  email           text check (email is null or email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  address         text check (address is null or char_length(address) <= 300),
  is_archived     boolean not null default false,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  created_by      uuid references public.profiles (id) on delete set null
);
create index customers_created_at_idx on public.customers (created_at desc, id desc);

create table public.suppliers (
  id              bigint generated always as identity primary key,
  name            text not null check (char_length(btrim(name)) between 2 and 150),
  contact_person  text check (contact_person is null or char_length(contact_person) <= 120),
  contact_number  text check (contact_number is null or char_length(contact_number) <= 40),
  email           text check (email is null or email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  address         text check (address is null or char_length(address) <= 300),
  is_archived     boolean not null default false,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  created_by      uuid references public.profiles (id) on delete set null
);
create index suppliers_created_at_idx on public.suppliers (created_at desc, id desc);

-- ---------------------------------------------------------------------------
-- Sales
-- ---------------------------------------------------------------------------
create table public.sales (
  id                 bigint generated always as identity primary key,
  reference_no       text not null check (char_length(btrim(reference_no)) between 1 and 60),
  client_request_id  uuid unique,                 -- idempotency key: prevents double submission
  customer_id        bigint references public.customers (id) on delete restrict,
  customer_name      text,                        -- snapshot
  sold_at            timestamptz not null default now(),
  item_count         integer not null check (item_count > 0),
  total_quantity     integer not null check (total_quantity > 0),
  total_amount       numeric(14,2) not null check (total_amount >= 0),
  notes              text check (notes is null or char_length(notes) <= 500),
  created_by         uuid references public.profiles (id) on delete set null,
  created_by_name    text not null,
  created_at         timestamptz not null default now()
);
create unique index sales_reference_key on public.sales (lower(btrim(reference_no)));
create index sales_sold_at_idx on public.sales (sold_at desc);
create index sales_customer_idx on public.sales (customer_id);

create table public.sale_items (
  id             bigint generated always as identity primary key,
  sale_id        bigint not null references public.sales (id) on delete restrict,
  product_id     bigint not null references public.products (id) on delete restrict,
  product_name   text not null,
  product_sku    text not null,
  quantity       integer not null check (quantity > 0),
  unit_price     numeric(12,2) not null check (unit_price >= 0),
  line_total     numeric(14,2) generated always as (quantity * unit_price) stored,
  unique (sale_id, product_id)
);
create index sale_items_product_idx on public.sale_items (product_id);

-- ---------------------------------------------------------------------------
-- Stock movement ledger (immutable, append-only)
-- ---------------------------------------------------------------------------
create table public.stock_movements (
  id                    bigint generated always as identity primary key,
  movement_type         public.movement_type not null,
  product_id            bigint not null references public.products (id) on delete restrict,
  -- Historical snapshots: reports stay correct after renames / recategorisation
  product_name          text not null,
  product_sku           text not null,
  category_id           bigint not null references public.categories (id) on delete restrict,
  category_name         text not null,
  quantity_change       integer not null check (quantity_change <> 0),
  quantity_before       integer not null check (quantity_before >= 0),
  quantity_after        integer not null check (quantity_after >= 0),
  unit_cost             numeric(12,2) check (unit_cost is null or unit_cost >= 0),
  unit_price            numeric(12,2) check (unit_price is null or unit_price >= 0),
  supplier_id           bigint references public.suppliers (id) on delete restrict,
  customer_id           bigint references public.customers (id) on delete restrict,
  sale_id               bigint references public.sales (id) on delete restrict,
  reverses_movement_id  bigint unique references public.stock_movements (id) on delete restrict,
  reference_no          text check (reference_no is null or char_length(reference_no) <= 60),
  reason                text check (reason is null or char_length(reason) <= 500),
  occurred_at           timestamptz not null default now(),
  created_at            timestamptz not null default now(),
  created_by            uuid references public.profiles (id) on delete restrict,
  created_by_name       text not null,
  constraint stock_movements_balance_chk check (quantity_after = quantity_before + quantity_change),
  constraint stock_movements_sign_chk check (
    case movement_type
      when 'stock_in' then quantity_change > 0
      when 'sale' then quantity_change < 0
      when 'damaged' then quantity_change < 0
      when 'lost' then quantity_change < 0
      when 'other_out' then quantity_change < 0
      else true
    end),
  constraint stock_movements_sale_link_chk check ((movement_type = 'sale') = (sale_id is not null))
);
create index stock_movements_occurred_idx on public.stock_movements (occurred_at desc, id desc);
create index stock_movements_product_idx on public.stock_movements (product_id, occurred_at);
create index stock_movements_category_idx on public.stock_movements (category_id, occurred_at);
create index stock_movements_type_idx on public.stock_movements (movement_type, occurred_at);
create index stock_movements_supplier_idx on public.stock_movements (supplier_id) where supplier_id is not null;
create index stock_movements_customer_idx on public.stock_movements (customer_id) where customer_id is not null;
create index stock_movements_sale_idx on public.stock_movements (sale_id) where sale_id is not null;

